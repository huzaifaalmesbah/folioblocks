/**
 * Bundle the command line (src/cli/folioblocks.ts) into one file,
 * cli/folioblocks.mjs, so it runs with plain Node: from this repo
 * (`npx github:huzaifaalmesbah/folioblocks`) or a published package, with
 * no build step and no dev tools. It finds the fonts and images in public/.
 *
 * The bundle is committed; CI checks it matches the source.
 * Usage: npm run build:cli            (write it)
 *        npm run build:cli -- --check (fail if it is out of date)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'rolldown';

const OUT = 'cli/folioblocks.mjs';
const check = process.argv.includes('--check');

const result = await build({
  input: 'src/cli/folioblocks.ts',
  platform: 'node',
  write: false,
  output: { format: 'esm', banner: '#!/usr/bin/env node\n// Generated by `npm run build:cli` from src/cli/folioblocks.ts. Do not edit.' },
});
const code = result.output[0].code;

let current = '';
try {
  current = readFileSync(OUT, 'utf8');
} catch {
  // Not built yet.
}

if (check) {
  if (current !== code) {
    console.error(`${OUT} is out of date. Run \`npm run build:cli\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  writeFileSync(OUT, code, { mode: 0o755 });
  console.log(`${OUT}: ${Math.round(code.length / 1024)} KB`);
}
